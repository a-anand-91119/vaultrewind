from pathlib import Path
from typing import Protocol


class DatabaseAdapter(Protocol):
    def normalize(self, data_root: Path) -> dict: ...
    def validate(self, data_root: Path) -> dict: ...


class DeploymentAdapter(Protocol):
    async def request(self, verb: str, instance_id: str, operation_id: str,
                      fencing_token: int, payload: dict | None = None) -> dict: ...


class RepositoryAdapter(Protocol):
    def initialize(self) -> dict: ...
    def list_snapshots(self) -> list[dict]: ...
    def commit(self, root: Path, snapshot_uuid: str, captured_at: str) -> dict: ...
    def restore(self, restic_id: str, target: Path) -> dict: ...
    def read_manifest(self, restic_id: str) -> dict: ...
    def check(self, read_data: bool = False) -> dict: ...
    def forget(self, ids: list[str]) -> dict: ...


class SQLiteAdapter:
    def normalize(self, data_root: Path) -> dict:
        from .sqlite import normalize_sqlite
        return normalize_sqlite(data_root)

    def validate(self, data_root: Path) -> dict:
        from .sqlite import validate_sqlite
        return validate_sqlite(data_root)
