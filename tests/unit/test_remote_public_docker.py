"""Opt-in disposable real Docker publication and activation-boundary regressions.

No daemon changes, shared fixtures, or systemd claims. All containers, bind data
and networks are generated by this test and removed after preserving assertions.
"""
import json
import os
import shutil
import socket
import tempfile
import time
import uuid
from pathlib import Path

import pytest

from vaultrewind.core.errors import VaultRewindError
from vaultrewind.remote.docker import Docker, validate_public_network
from vaultrewind.remote.helper import Helper
from vaultrewind.remote.journal import Journal
from vaultrewind.remote.policy import Policy
from vaultrewind.remote.protocol import Request

pytestmark = [pytest.mark.docker, pytest.mark.skipif(os.environ.get('VAULTREWIND_REMOTE_PUBLIC_DOCKER_TEST') != '1', reason='opt-in disposable public-port Docker regression')]


class Recovery:
    def disarm(self, journal):
        journal.value['watchdog_armed'] = False
        journal.save()


def test_internal_bridge_vs_published_nat_and_failure_preserves_active_generation(monkeypatch):
    docker = Docker()
    iid, operation = str(uuid.uuid4()), str(uuid.uuid4())
    label = {'org.vaultrewind.test': iid}
    root = Path(tempfile.mkdtemp(prefix='vrw-public-', dir=Path(__file__).parent))
    image = docker.image('ghcr.io/dani-garcia/vaultwarden:1.37.4')['Id']
    containers, networks, evidence = [], [], {'daemon_version': docker.api('GET', '/version')['Version']}
    try:
        with socket.socket() as listener:
            listener.bind(('127.0.0.1', 0))
            host_port = str(listener.getsockname()[1])
        ports = {'80/tcp': [{'HostIp': '127.0.0.1', 'HostPort': host_port}]}
        for internal in (True, False):
            name = 'vrw-public-' + iid + ('-internal' if internal else '-nat')
            network = docker.api('POST', '/networks/create', {'Name': name, 'Internal': internal, 'Labels': label})['Id']
            networks.append(network)
            data = root / ('internal' if internal else 'nat')
            data.mkdir(mode=0o700)
            cid = docker.create(name, {'Image': image, 'Healthcheck': {'Test': ['NONE']}, 'Labels': label,
                'HostConfig': {'NetworkMode': name, 'PortBindings': ports, 'RestartPolicy': {'Name': 'no'},
                               'Mounts': [{'Type': 'bind', 'Source': str(data), 'Target': '/data'}]}})
            containers.append(cid)
            docker.start(cid)
            assert docker.health(cid, 60)['internal_http_alive']
            if internal:
                with pytest.raises(VaultRewindError) as error:
                    validate_public_network(docker, name, ports)
                assert error.value.code == 'PUBLIC_NETWORK_UNPUBLISHABLE'
                actual = docker.inspect(cid)['NetworkSettings']['Ports']
                evidence['internal_actual_ports_present'] = bool(actual)
                # This records the actual Engine behavior, not an assumed version regression.
                try:
                    docker.public_health(cid, ports, 2)
                except VaultRewindError as error:
                    evidence['internal_public_error'] = error.code
                else:
                    evidence['internal_public_error'] = None
                docker.stop(cid, timeout=120)
            else:
                validate_public_network(docker, name, ports)
                proof = docker.public_health(cid, ports, 10)
                assert proof['public_ports_verified'] and proof['public_endpoint_verified']
                evidence['nat_public_verified'] = True
                docker.stop(cid, timeout=120)
                # Isolated journal at the real publication boundary. The complete
                # capture/safety path is covered separately by real lifecycle tests.
                state = root / 'state'
                state.mkdir(mode=0o700)
                target = root / 'restored'
                target.mkdir(mode=0o700)
                mount = {'type': 'bind', 'source': str(target), 'target': '/data', 'read_only': False, 'snapshot_path': 'data'}
                target_name = 'vrw-public-active-' + iid
                value = {'container_id': None, 'container_name': target_name, 'ownership': 'exclusive', 'external_dependencies_ready': True,
                         'allowed_operations': ['status', 'commit_restore'], 'allowed_image_ids': [image], 'allowed_networks': [name],
                         'port_bindings': ports, 'mounts': [mount], 'validation_window': 30}
                policy = Policy({'schema_version': 1, 'machine_id': Path('/etc/machine-id').read_text().strip(),
                                 'daemon_id': docker.info()['ID'], 'instances': {iid: value}}, state)
                helper = Helper(policy, docker, Recovery())
                journal = Journal(state, operation)
                journal.create(Request(iid, operation, 1, 'test', 'commit_restore', {}), [], kind='restore')
                original = {'source_state': 'absent', 'container_id': None, 'mounts': [mount]}
                descriptor = {'image_id': image, 'config': {'Healthcheck': {'Test': ['NONE']}},
                              'host_config': {'NetworkMode': name, 'PortBindings': ports, 'RestartPolicy': {'Name': 'no'}}}
                journal.transition('candidate_validated', original=original, source_state='absent', start_on_completion=True,
                                   watchdog_armed=True, deadline=time.time() + 600, monotonic_deadline=time.monotonic() + 600,
                                   boot_id=Path('/proc/sys/kernel/random/boot_id').read_text().strip(), restore_descriptor=descriptor,
                                   generation_steps=[{'mount': mount, 'new': str(target), 'phase': 'switched'}])
                # TEST ONLY fault: host probe becomes unavailable after the container
                # starts. Docker allocation/internal readiness are real and successful.
                real_public = docker.public_health
                def unavailable(*args, **kwargs):
                    raise VaultRewindError('PUBLIC_ENDPOINT_UNAVAILABLE', 'Synthetic post-publication endpoint failure')
                monkeypatch.setattr(docker, 'public_health', unavailable)
                with pytest.raises(VaultRewindError) as error:
                    helper.activate(policy.instance(iid), journal)
                assert error.value.code == 'PUBLIC_ENDPOINT_UNAVAILABLE'
                final_id = journal.value['final_id']
                containers.append(final_id)
                assert docker.inspect(final_id)['State']['Running']
                (target / 'post-publication-write').write_text('synthetic write must survive reconciliation')
                identity = target.stat().st_ino
                result = helper._recover_locked(policy.instance(iid), journal, 'test')
                assert result['phase'] == 'needs_attention' and result['activation_started']
                assert target.stat().st_ino == identity
                assert (target / 'post-publication-write').read_text() == 'synthetic write must survive reconciliation'
                assert docker.inspect(final_id)['State']['Running']
                evidence['postactivation_failure_preserved_generation'] = True
                monkeypatch.setattr(docker, 'public_health', real_public)
                recovered = helper._recover_locked(policy.instance(iid), journal, 'test')
                assert recovered['phase'] == 'complete' and recovered['public_endpoint_verified']
                evidence['reconciled_only_after_public_verification'] = True
        print('PUBLIC_READINESS_EVIDENCE=' + json.dumps(evidence, sort_keys=True))
    finally:
        for item in docker.containers():
            if item.get('Labels', {}).get('org.vaultrewind.operation') == operation and item['Id'] not in containers:
                containers.append(item['Id'])
        for cid in reversed(containers):
            item = docker.inspect(cid, missing=True)
            if item:
                assert item['Config'].get('Labels', {}).get('org.vaultrewind.test') == iid or item['Config'].get('Labels', {}).get('org.vaultrewind.operation') == operation
                if item['State']['Running']:
                    docker.stop(cid, timeout=120)
                docker.remove(cid)
        for network in networks:
            docker.api('DELETE', '/networks/' + network)
        shutil.rmtree(root)
